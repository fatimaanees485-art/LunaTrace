import { getAccessToken } from './firebaseAuth';

export interface DriveFileItem {
  id: string;
  name: string;
  mimeType: string;
  modifiedTime?: string;
  size?: string;
  webViewLink?: string;
  iconLink?: string;
  description?: string;
}

const DRIVE_API_URL = 'https://www.googleapis.com/drive/v3';
const DRIVE_UPLOAD_URL = 'https://www.googleapis.com/upload/drive/v3';

const LUNATRACE_FOLDER_NAME = 'LunaTrace Mission Data';

/**
 * Ensures user has an active access token, otherwise throws an error
 */
async function requireAccessToken(): Promise<string> {
  const token = await getAccessToken();
  if (!token) {
    throw new Error('Google Drive access token is not available. Please sign in with Google first.');
  }
  return token;
}

/**
 * Locates or creates a dedicated "LunaTrace Mission Data" folder in the user's Google Drive.
 */
export async function getOrCreateLunaTraceFolder(): Promise<string> {
  const token = await requireAccessToken();

  // Search if folder already exists in root or Drive
  const query = encodeURIComponent(
    `name = '${LUNATRACE_FOLDER_NAME}' and mimeType = 'application/vnd.google-apps.folder' and trashed = false`
  );

  const searchRes = await fetch(`${DRIVE_API_URL}/files?q=${query}&fields=files(id, name)&spaces=drive`, {
    headers: { Authorization: `Bearer ${token}` }
  });

  if (!searchRes.ok) {
    const err = await searchRes.json().catch(() => ({}));
    throw new Error(err?.error?.message || `Failed to search folders (${searchRes.status})`);
  }

  const searchData = await searchRes.json();
  if (searchData.files && searchData.files.length > 0) {
    return searchData.files[0].id;
  }

  // Create folder
  const createRes = await fetch(`${DRIVE_API_URL}/files`, {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${token}`,
      'Content-Type': 'application/json'
    },
    body: JSON.stringify({
      name: LUNATRACE_FOLDER_NAME,
      mimeType: 'application/vnd.google-apps.folder',
      description: 'Directory for LunaTrace lunar landing site assessments and rover traverses.'
    })
  });

  if (!createRes.ok) {
    const err = await createRes.json().catch(() => ({}));
    throw new Error(err?.error?.message || `Failed to create folder (${createRes.status})`);
  }

  const newFolder = await createRes.json();
  return newFolder.id;
}

/**
 * Uploads a text/json/csv file to Google Drive (optionally inside the LunaTrace folder).
 */
export async function uploadFileToDrive(options: {
  filename: string;
  content: string;
  mimeType: string;
  description?: string;
  saveToDedicatedFolder?: boolean;
}): Promise<DriveFileItem> {
  const token = await requireAccessToken();

  let parentFolderId: string | null = null;
  if (options.saveToDedicatedFolder !== false) {
    try {
      parentFolderId = await getOrCreateLunaTraceFolder();
    } catch (folderErr) {
      console.warn('Could not retrieve/create LunaTrace folder, falling back to Drive root:', folderErr);
    }
  }

  const metadata: Record<string, any> = {
    name: options.filename,
    mimeType: options.mimeType,
    description: options.description || 'Generated by LunaTrace Navigator'
  };

  if (parentFolderId) {
    metadata.parents = [parentFolderId];
  }

  // Use multipart upload to send metadata + content in one request
  const boundary = '-------314159265358979323846';
  const delimiter = `\r\n--${boundary}\r\n`;
  const closeDelimiter = `\r\n--${boundary}--`;

  const multipartRequestBody =
    delimiter +
    'Content-Type: application/json; charset=UTF-8\r\n\r\n' +
    JSON.stringify(metadata) +
    delimiter +
    `Content-Type: ${options.mimeType}\r\n\r\n` +
    options.content +
    closeDelimiter;

  const uploadRes = await fetch(
    `${DRIVE_UPLOAD_URL}/files?uploadType=multipart&fields=id,name,mimeType,modifiedTime,size,webViewLink,iconLink`,
    {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${token}`,
        'Content-Type': `multipart/related; boundary=${boundary}`
      },
      body: multipartRequestBody
    }
  );

  if (!uploadRes.ok) {
    const errData = await uploadRes.json().catch(() => ({}));
    throw new Error(errData?.error?.message || `Failed to upload file (${uploadRes.status})`);
  }

  return await uploadRes.json();
}

/**
 * Lists files in Google Drive. Supports filtering for LunaTrace files or all files.
 */
export async function listDriveFiles(filterByLunaTrace = true): Promise<DriveFileItem[]> {
  const token = await requireAccessToken();

  let query = 'trashed = false';
  if (filterByLunaTrace) {
    // Look for files with LunaTrace in name or inside LunaTrace folder
    query += " and (name contains 'LunaTrace' or fullText contains 'LunaTrace')";
  }

  const url = `${DRIVE_API_URL}/files?q=${encodeURIComponent(query)}&orderBy=modifiedTime desc&pageSize=30&fields=files(id,name,mimeType,modifiedTime,size,webViewLink,iconLink,description)`;

  const res = await fetch(url, {
    headers: { Authorization: `Bearer ${token}` }
  });

  if (!res.ok) {
    const errData = await res.json().catch(() => ({}));
    throw new Error(errData?.error?.message || `Failed to fetch Drive files (${res.status})`);
  }

  const data = await res.json();
  return data.files || [];
}

/**
 * Downloads file content as text
 */
export async function downloadDriveFileContent(fileId: string): Promise<string> {
  const token = await requireAccessToken();
  const res = await fetch(`${DRIVE_API_URL}/files/${fileId}?alt=media`, {
    headers: { Authorization: `Bearer ${token}` }
  });

  if (!res.ok) {
    throw new Error(`Failed to download file content (${res.status})`);
  }

  return await res.text();
}

/**
 * Deletes a file from Google Drive.
 * (MUST only be called after explicit user confirmation in UI)
 */
export async function deleteDriveFile(fileId: string): Promise<void> {
  const token = await requireAccessToken();
  const res = await fetch(`${DRIVE_API_URL}/files/${fileId}`, {
    method: 'DELETE',
    headers: { Authorization: `Bearer ${token}` }
  });

  if (!res.ok && res.status !== 204) {
    const errData = await res.json().catch(() => ({}));
    throw new Error(errData?.error?.message || `Failed to delete file from Google Drive (${res.status})`);
  }
}
